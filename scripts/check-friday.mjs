import assert from 'node:assert/strict';
import {FRIDAY_HADITHS,FRIDAY_DHIKR,FRIDAY_SALAWAT,isFridayDate,fridayContent} from '../assets/friday-content.js';
import {dailyContent,resolveContent,hasCardMessage} from '../assets/daily.js';
const config={card:{quote:'نص عادي',attribution:'كاتب'},settings:{showQuote:true},content:{mode:'daily',showHadith:true,showDua:false,offset:0,fridayEnabled:true,fridayReminders:true}};
assert.equal(isFridayDate('2026-11-13'),true);
assert.equal(isFridayDate('2026-11-12'),false);
assert.equal(isFridayDate('2026-11-14'),false);
assert(FRIDAY_HADITHS.length>=3&&FRIDAY_DHIKR.length>=5&&FRIDAY_SALAWAT.length>=3);
const today=dailyContent(config,'2026-11-13'),next=dailyContent(config,'2026-11-20');
assert.equal(today.special,'friday');assert(today.hadith?.url?.startsWith('https://sunnah.com/'));
assert(today.dua?.text.includes(' • '));
assert.notEqual(today.hadith?.id,next.hadith?.id);
assert.notEqual(today.dhikr?.id,next.dhikr?.id);
assert.equal(dailyContent(config,'2026-11-14').special,undefined);
assert.equal(dailyContent(config,'2026-11-14').dua,null);
const special=resolveContent({...config,content:{...config.content,mode:'manual'}},'2026-11-13');
assert.equal(special.daily.special,'friday');assert.equal(hasCardMessage(special),true);
const disabled=resolveContent({...config,content:{...config.content,fridayEnabled:false,mode:'manual'}},'2026-11-13');
assert.equal(disabled.daily,undefined);assert.equal(disabled.card.quote,'نص عادي');
assert.equal(dailyContent({...config,content:{...config.content,fridayReminders:false}},'2026-11-13').dua,null);
assert.equal(fridayContent('2026-11-14'),null);
console.log('PASS: Friday rotation and settings');
